import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const url=process.env.PREVIZ_TEST_URL||'http://127.0.0.1:4177';
const output=path.resolve('2026-10-04-v1.6.0-verification',new Date().toISOString().replace(/[:.]/g,'-'));
await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[],results=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',dialog=>dialog.accept());
const check=(name,value)=>{assert.ok(value,name);results.push(name);console.log('PASS '+name);};
const scene=()=>page.evaluate(()=>__PREVIZ__.getScene());
const preview=()=>page.locator('#shot-preview canvas').evaluate(c=>c.toDataURL());
const reveal=async selector=>{
  await page.locator(selector).evaluate(el=>{for(let p=el.parentElement;p;p=p.parentElement)if(p.tagName==='DETAILS')p.open=true;});
};
try{
  await page.goto(url);await page.waitForFunction(()=>window.__PREVIZ__);
  check('version 1.6.0',await page.evaluate(()=>__PREVIZ__.build.appVersion==='1.6.0'));
  check('Three.js mannequin renderer',await page.evaluate(()=>__PREVIZ__.getEngine().actorRigs?.size===2));
  check('scene description always visible',await page.locator('#scene-description').isVisible());
  check('description inside desktop viewport',await page.locator('#scene-description').evaluate(e=>e.getBoundingClientRect().bottom<=innerHeight));
  check('shot preview visible and 16:9',await page.locator('#shot-preview canvas').evaluate(c=>c.clientWidth>100&&Math.abs(c.clientWidth/c.clientHeight-16/9)<.03));
  check('default 2 actors with umbrella',await scene().then(d=>d.actors.length===2&&d.props.some(p=>p.type==='umbrella')));
  await page.screenshot({path:path.join(output,'2026-10-04-initial-desktop.png'),fullPage:true});
  await page.locator('#scene-description').fill('비가 내리는 한밤의 편의점 앞, 우산을 쓴 남자에게 여자가 다가온다.');
  await reveal('#blocking-duration');await page.locator('#blocking-duration').fill('4');
  await page.locator('#generate').click();
  await page.waitForFunction(()=>__PREVIZ__.getScene().sequence.duration===4);
  check('structured composition retains description',await scene().then(d=>d.actors.length===2&&d.supplementaryPrompt.includes('비가')));
  await page.evaluate(()=>__PREVIZ__.getEngine().seek(4));
  const before=await preview();const position=await scene();
  await reveal('#cam-x');
  const x=Number(await page.locator('#cam-x').inputValue());
  await page.locator('#cam-x').fill(String(x+2));await page.locator('#cam-x').press('Tab');
  await page.waitForFunction(()=>__PREVIZ__.getScene().shots[0].camera.manual?.enabled);
  await page.waitForTimeout(150);
  const edited=await scene();const manual=edited.shots[0].camera.manual;
  check('whole shot camera static preserved',manual.start.every((n,i)=>Math.abs(n-manual.end[i])<1e-6));
  check('camera numeric edit changes preview at end',before!==await preview());
  const shotBefore=await page.evaluate(()=>__PREVIZ__.getEngine().shotCamera.position.toArray());
  const viewportBox=await page.locator('#viewport canvas').boundingBox();
  await page.mouse.move(viewportBox.x+viewportBox.width*.85,viewportBox.y+viewportBox.height*.3);
  await page.mouse.down();await page.mouse.move(viewportBox.x+viewportBox.width*.70,viewportBox.y+viewportBox.height*.42,{steps:8});await page.mouse.up();
  const shotAfterOrbit=await page.evaluate(()=>__PREVIZ__.getEngine().shotCamera.position.toArray());
  check('work orbit does not silently alter shot',shotBefore.every((n,i)=>Math.abs(n-shotAfterOrbit[i])<1e-6));
  await page.locator('#copy-director-camera').click();await page.waitForTimeout(150);
  check('copy working view updates actual camera',await page.evaluate(()=>{
    const e=__PREVIZ__.getEngine();return e.shotCamera.position.distanceTo(e.directorCamera.position)<.001;
  }));
  const actorId=(await scene()).actors[1].id;
  await page.locator('#edit-target').selectOption(actorId);
  check('actor contextual controls shown',await page.locator('#actor-transform-controls').isVisible());
  check('camera controls hidden for actor',!(await page.locator('#camera-transform-controls').isVisible()));
  check('selected actor matches action editor',await page.locator('#action-actor').inputValue()===actorId);
  await reveal('#action-index');
  const walkIndex=await scene().then(d=>d.actors[1].actions.findIndex(a=>a.type==='walk'));
  await page.locator('#action-index').selectOption(String(walkIndex));
  const z=Number(await page.locator('#action-to-z').inputValue());
  await page.locator('#action-to-z').fill(String(z+.4));await page.locator('#apply-action').click();
  check('actor arrival edit applied',await scene().then(d=>Math.abs(d.actors[1].actions[walkIndex].to[2]-z-.4)<1e-6));
  await page.locator('#edit-target').selectOption('camera');
  await page.screenshot({path:path.join(output,'2026-10-04-desktop.png'),fullPage:true});
  await reveal('#export-prompt');const txtEvent=page.waitForEvent('download');await page.locator('#export-prompt').click();
  const txt=await txtEvent;await txt.saveAs(path.join(output,'2026-10-04-supplemental.txt'));
  await reveal('#ref-mid');const pngEvent=page.waitForEvent('download');await page.locator('#ref-mid').click();
  const png=await pngEvent;await png.saveAs(path.join(output,'2026-10-04-reference.png'));
  await reveal('#render-video');const videoEvent=page.waitForEvent('download',{timeout:180000});await page.locator('#render-video').click();
  check('video export locks scene edits and PNG capture',await page.evaluate(()=>{
    const locked=e=>e.disabled||Boolean(e.closest('[inert]'));
    return locked(document.querySelector('#cam-x'))&&locked(document.querySelector('#scene-description'))&&locked(document.querySelector('#ref-mid'));
  }));
  const video=await videoEvent;const videoFile=path.join(output,'2026-10-04-reference.'+video.suggestedFilename().split('.').at(-1));
  await video.saveAs(videoFile);check('video download completes',!(await video.failure()));
  check('video export releases editor lock',await page.evaluate(()=>{const e=document.querySelector('#scene-description');return !e.disabled&&!e.closest('[inert]');}));
  await page.setViewportSize({width:390,height:844});
  check('mobile no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  check('mobile description accessible',await page.locator('#scene-description').isVisible());
  await page.screenshot({path:path.join(output,'2026-10-04-mobile.png'),fullPage:true});
  check('no uncaught browser errors',errors.length===0);
  await writeFile(path.join(output,'2026-10-04-results.json'),JSON.stringify({results,errors,videoFile},null,2));
  console.log('OUTPUT '+output);
}finally{await browser.close();}
